#!/usr/bin/env python3
"""Generate `crates/gpui/src/icons/lucide_generated.rs` from `crates/gpui/assets/lucide/*.svg`."""

import glob
import os

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS_DIR = os.path.join(REPO_ROOT, "crates", "gpui", "assets", "lucide")
OUTPUT_FILE = os.path.join(REPO_ROOT, "crates", "gpui", "src", "icons", "lucide_generated.rs")


def to_pascal_case(kebab: str) -> str:
    return "".join(part.capitalize() for part in kebab.split("-"))


def main() -> None:
    svg_files = sorted(glob.glob(os.path.join(ASSETS_DIR, "*.svg")))
    if not svg_files:
        raise RuntimeError(f"No .svg files found in {ASSETS_DIR}")

    entries = []
    for path in svg_files:
        name = os.path.splitext(os.path.basename(path))[0]
        variant = to_pascal_case(name)
        entries.append((name, variant))

    # Ensure strictly sorted by kebab-case name for binary search
    entries.sort(key=lambda item: item[0])

    out = []
    out.append("// @generated by scripts/generate_lucide.py. Do not edit manually.")
    out.append("//")
    out.append("// Lucide icons are licensed under the ISC License (with portions derived from")
    out.append("// Feather Icons under the MIT License). See `crates/gpui/assets/lucide/LICENSE`.")
    out.append("")
    out.append("use std::fmt;")
    out.append("use std::str::FromStr;")
    out.append("")
    out.append("/// All Lucide SVG icons bundled directly from `crates/gpui/assets/lucide/*.svg`.")
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    out.append("#[repr(u16)]")
    out.append("pub enum LucideIcon {")
    for name, variant in entries:
        out.append(f"    /// Lucide `{name}` icon.")
        out.append(f"    {variant},")
    out.append("}")
    out.append("")

    out.append("static NAMES: [&str; LucideIcon::COUNT] = [")
    for name, _ in entries:
        out.append(f'    "{name}",')
    out.append("];")
    out.append("")

    out.append("static ASSET_PATHS: [&str; LucideIcon::COUNT] = [")
    for name, _ in entries:
        out.append(f'    "lucide/{name}.svg",')
    out.append("];")
    out.append("")

    out.append("static SVG_STRS: [&str; LucideIcon::COUNT] = [")
    for name, _ in entries:
        out.append(f'    include_str!("../../assets/lucide/{name}.svg"),')
    out.append("];")
    out.append("")

    out.append("impl LucideIcon {")
    out.append(f"    /// Total number of bundled Lucide icons ({len(entries)}).")
    out.append(f"    pub const COUNT: usize = {len(entries)};")
    out.append("")
    out.append("    /// Every bundled Lucide icon in alphabetical kebab-case order.")
    out.append("    pub const ALL: &'static [LucideIcon] = &[")
    for _, variant in entries:
        out.append(f"        LucideIcon::{variant},")
    out.append("    ];")
    out.append("")
    out.append("    /// Returns the canonical kebab-case Lucide icon name (e.g. `\"chevron-down\"`).")
    out.append("    #[inline]")
    out.append("    pub fn name(self) -> &'static str {")
    out.append("        NAMES[self as usize]")
    out.append("    }")
    out.append("")
    out.append("    /// Returns the asset path for use with `LucideAssetSource` (e.g. `\"lucide/chevron-down.svg\"`).")
    out.append("    #[inline]")
    out.append("    pub fn asset_path(self) -> &'static str {")
    out.append("        ASSET_PATHS[self as usize]")
    out.append("    }")
    out.append("")
    out.append("    /// Returns the raw SVG source string copied directly from Lucide.")
    out.append("    #[inline]")
    out.append("    pub fn svg_str(self) -> &'static str {")
    out.append("        SVG_STRS[self as usize]")
    out.append("    }")
    out.append("")
    out.append("    /// Returns the raw SVG bytes copied directly from Lucide.")
    out.append("    #[inline]")
    out.append("    pub fn svg_bytes(self) -> &'static [u8] {")
    out.append("        SVG_STRS[self as usize].as_bytes()")
    out.append("    }")
    out.append("")
    out.append("    /// Looks up a Lucide icon by its kebab-case name (e.g. `\"arrow-right\"`),")
    out.append("    /// optionally prefixed with `\"lucide/\"` and/or suffixed with `\".svg\"`.")
    out.append("    pub fn from_name(name: &str) -> Option<Self> {")
    out.append('        let trimmed = name.trim();')
    out.append('        let stripped = trimmed.strip_prefix("lucide/").unwrap_or(trimmed);')
    out.append('        let canonical = stripped.strip_suffix(".svg").unwrap_or(stripped);')
    out.append("        NAMES")
    out.append("            .binary_search(&canonical)")
    out.append("            .ok()")
    out.append("            .map(|idx| Self::ALL[idx])")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("impl fmt::Display for LucideIcon {")
    out.append("    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {")
    out.append("        f.write_str(self.name())")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("/// Error returned when parsing an unknown Lucide icon name.")
    out.append("#[derive(Clone, Debug, PartialEq, Eq)]")
    out.append("pub struct UnknownLucideIcon(pub String);")
    out.append("")
    out.append("impl fmt::Display for UnknownLucideIcon {")
    out.append("    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {")
    out.append('        write!(f, "unknown Lucide icon: `{}`", self.0)')
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("impl std::error::Error for UnknownLucideIcon {}")
    out.append("")
    out.append("impl FromStr for LucideIcon {")
    out.append("    type Err = UnknownLucideIcon;")
    out.append("")
    out.append("    fn from_str(s: &str) -> Result<Self, Self::Err> {")
    out.append("        Self::from_name(s).ok_or_else(|| UnknownLucideIcon(s.to_owned()))")
    out.append("    }")
    out.append("}")
    out.append("")

    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    with open(OUTPUT_FILE, "w") as f:
        f.write("\n".join(out))

    print(f"Generated {OUTPUT_FILE} with {len(entries)} Lucide icons")


if __name__ == "__main__":
    main()
